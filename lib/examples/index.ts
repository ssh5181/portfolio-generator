/** First line of an example, for a short grey hint. */
export function hint(text: string | undefined, maxLen = 90): string {
  if (!text) return "";
  const first = text.split("\n")[0].replace(/^·\s*/, "");
  return first.length > maxLen ? first.slice(0, maxLen - 1) + "…" : first;
}
